import assert from 'node:assert/strict';
const { chromium } = await import(process.env.IAM_PLAYWRIGHT_MODULE);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const origin = process.env.IAM_BROWSER_URL;
const project = process.env.IAM_BROWSER_PROJECT;
try {
  await page.goto(`${origin}/security/${project}/live`);
  await page.locator('#flow-email').fill(process.env.IAM_BROWSER_EMAIL);
  await page.locator('#flow-password').fill('Sup3rStr0ng!Pass');
  await page.getByRole('button', { name: 'Sign in', exact: true }).last().click();
  await page.getByText('Аккаунт будет удалён через 7 дн.', { exact: false }).waitFor();
  await page.getByLabel('Текущий пароль', { exact: true }).fill('Sup3rStr0ng!Pass');
  await page.getByRole('button', { name: 'Запланировать удаление', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Удаление назначено' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Отменить удаление', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Обновить активность', exact: true }).click();
  await page.evaluate(key => sessionStorage.setItem('iam.masterKey', key), process.env.IAM_BROWSER_MASTER_KEY);
  await page.goto(`${origin}/projects/${project}/config`);
  await page.getByRole('tab', { name: 'Account deletion', exact: true }).click();
  assert.equal(await page.getByLabel('Cancellation period (days)').inputValue(), '7');
  await page.getByLabel('Cancellation period (days)').fill('14');
  await page.getByRole('button', { name: 'Save deletion policy', exact: true }).click();
  await page.getByText('Deletion policy saved', { exact: true }).waitFor();
  await page.goto(`${origin}/projects/${project}/users`);
  await page.getByText('Scheduled', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Open menu', exact: true }).first().click();
  await page.getByRole('menuitem', { name: 'View detail', exact: true }).click();
  await page.getByRole('button', { name: 'Deletion', exact: true }).click();
  await page.getByText('Deletion history', { exact: true }).waitFor();
  await page.getByText('7 days remaining.', { exact: false }).waitFor();
  await page.screenshot({ path: '/tmp/iam-deletion-admin.png', fullPage: true });
  await page.getByRole('button', { name: 'Cancel scheduled deletion', exact: true }).click();
  await page.getByLabel('Reason for cancellation', { exact: true }).fill('Support confirmed the user wants to keep the account');
  await page.getByRole('button', { name: 'Confirm cancellation', exact: true }).click();
  await page.getByText('Status: cancelled', { exact: true }).waitFor();
  await page.getByText('Support confirmed the user wants to keep the account', { exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/iam-deletion-admin-cancelled.png', fullPage: true });
  await page.goto(`${origin}/projects/${project}/users`);
  await page.getByText(process.env.IAM_BROWSER_EMAIL, { exact: true }).first().waitFor();
  assert.equal(await page.getByText('Scheduled', { exact: true }).count(), 0);
  await page.goto(`${origin}/security/${project}/live`);
  await page.getByRole('status').filter({ hasText: 'Удаление отменено' }).waitFor();
  await page.getByLabel('Текущий пароль', { exact: true }).fill('Sup3rStr0ng!Pass');
  await page.getByRole('button', { name: 'Запланировать удаление', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Удаление назначено' }).waitFor();
  await page.getByLabel('Текущий пароль', { exact: true }).fill('Sup3rStr0ng!Pass');
  await page.getByRole('button', { name: 'Отменить удаление', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Удаление отменено' }).waitFor();
  await page.getByRole('button', { name: 'Обновить активность', exact: true }).click();
  assert.deepEqual(errors, []);
  await page.screenshot({ path: '/tmp/iam-deletion-user.png', fullPage: true });
} catch (error) {
  console.error(await page.locator('body').innerText());
  throw error;
} finally { await browser.close(); }
